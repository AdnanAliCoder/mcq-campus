-- MCQ Campus pending signup schema
-- Required for verify-before-create registration flow.
-- Run once in Supabase SQL Editor before using the new signup flow.

BEGIN;

CREATE TABLE IF NOT EXISTS core_pendingsignup (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(254) NOT NULL UNIQUE,
    first_name varchar(150) NOT NULL,
    last_name varchar(150) NOT NULL,
    password_hash varchar(128) NOT NULL,
    code_hash varchar(64) NOT NULL,
    expires_at timestamptz NOT NULL,
    attempt_count smallint NOT NULL DEFAULT 0,
    last_sent_at timestamptz NOT NULL DEFAULT now(),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT core_pendingsignup_attempt_count_nonnegative CHECK (attempt_count >= 0)
);

CREATE INDEX IF NOT EXISTS core_pendingsignup_expires_at_idx
    ON core_pendingsignup (expires_at);

COMMIT;
